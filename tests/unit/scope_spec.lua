local Scope = T.load("core/scope.lua")
local Events = T.load("core/events.lua")
local Scheduler = T.load("core/scheduler.lua")

local function services()
	local errors = {}
	local bus = Events.New({ onError = function(err) errors[#errors + 1] = err end })
	local sched = Scheduler.New({ now = 0 })
	return bus, sched, errors
end

describe("scope", function()
	it("prefixes listener and job ids and tags timers", function()
		local bus, sched = services()
		local scope = Scope.New({ id = "rounds:round", events = bus, scheduler = sched })
		local a = scope:On("e", function() end)
		local b = scope:On("e", function() end, { id = "named", priority = 5 })
		expect(a.id):toBe("rounds:round:#1")
		expect(b.id):toBe("rounds:round:named")
		expect(b.priority):toBe(5)
		local job = scope:Every("think", 1, function() end)
		expect(job.id):toBe("rounds:round:think")
		local timer = scope:After(2, function() end)
		expect(timer.tag):toBe("rounds:round")
		expect(scope:IsAlive()):toBe(true)
	end)

	it("releases everything on Dispose", function()
		local bus, sched = services()
		local scope = Scope.New({ id = "s", events = bus, scheduler = sched })
		local calls = {}
		scope:On("e", function() calls[#calls + 1] = "event" end)
		scope:Every("job", 1, function() calls[#calls + 1] = "job" end)
		scope:After(1, function() calls[#calls + 1] = "timer" end)
		scope:Defer(function() calls[#calls + 1] = "deferred 1" end)
		scope:Defer(function(s) calls[#calls + 1] = "deferred 2 " .. s.id end)
		scope:Dispose()
		expect(calls):toEqual({ "deferred 2 s", "deferred 1" })
		bus:Emit("e")
		sched:Update(5)
		expect(#calls):toBe(2)
		expect(bus:Count()):toBe(0)
		expect(sched:Has("s:job")):toBe(false)
		expect(sched:Pending()):toBe(0)
		expect(scope:IsAlive()):toBe(false)
		scope:Dispose()
		expect(#calls):toBe(2)
	end)

	it("forgets fired timers", function()
		local bus, sched = services()
		local scope = Scope.New({ id = "s", events = bus, scheduler = sched })
		local fired = 0
		scope:After(1, function() fired = fired + 1 end)
		sched:Update(1)
		expect(fired):toBe(1)
		expect(next(scope.timers)):toBeNil()
	end)

	it("refuses new work after Dispose", function()
		local bus, sched = services()
		local scope = Scope.New({ id = "s", events = bus, scheduler = sched })
		scope:Dispose()
		expect(function() scope:On("e", function() end) end):toFail("scope 's': On('e') after Dispose")
		expect(function() scope:Every("j", 1, function() end) end):toFail("Every('j') after Dispose")
		expect(function() scope:After(1, function() end) end):toFail("After after Dispose")
		expect(function() scope:Defer(function() end) end):toFail("Defer after Dispose")
		expect(function() scope:Child("c") end):toFail("Child('c') after Dispose")
	end)

	it("disposes children with the parent, newest first", function()
		local bus, sched = services()
		local root = Scope.New({ id = "r", events = bus, scheduler = sched })
		local order = {}
		local first = root:Child("first")
		local second = root:Child("second")
		expect(first.id):toBe("r/first")
		first:Defer(function() order[#order + 1] = "first" end)
		second:Defer(function() order[#order + 1] = "second" end)
		root:Defer(function() order[#order + 1] = "root" end)
		local listener = second:On("e", function() end)
		expect(listener.id):toBe("r/second:#1")
		root:Dispose()
		expect(order):toEqual({ "second", "first", "root" })
		expect(first:IsAlive()):toBe(false)
		expect(bus:Count()):toBe(0)
	end)

	it("unlinks a child disposed on its own", function()
		local bus, sched = services()
		local root = Scope.New({ id = "r", events = bus, scheduler = sched })
		local child = root:Child("c")
		local other = root:Child("d")
		child:Dispose()
		expect(#root.children):toBe(1)
		expect(root.children[1]):toBe(other)
		expect(root.children[child]):toBeNil()
		root:Dispose()
		expect(other:IsAlive()):toBe(false)
	end)

	it("keeps running deferred callbacks when one fails", function()
		local bus, sched = services()
		local reported = {}
		local scope = Scope.New({
			id = "s", events = bus, scheduler = sched,
			onError = function(err, s) reported[#reported + 1] = s.id .. ": " .. err end,
		})
		local ran = false
		scope:Defer(function() ran = true end)
		scope:Defer(function() error("boom") end)
		scope:Dispose()
		expect(ran):toBe(true)
		expect(#reported):toBe(1)
		expect(reported[1]):toContain("boom")
	end)

	it("compacts released handles of long-lived scopes", function()
		local bus, sched = services()
		local scope = Scope.New({ id = "s", events = bus, scheduler = sched })
		for _ = 1, 500 do
			scope:On("e", function() end, { id = "same" })
			scope:Every("job", 1, function() end)
		end
		expect(#scope.listeners < 64):toBe(true)
		expect(#scope.jobs < 64):toBe(true)
		expect(bus:Count("e")):toBe(1)
		scope:Dispose()
		expect(bus:Count("e")):toBe(0)
		expect(sched:Has("s:job")):toBe(false)
	end)

	it("needs an id and the services it uses", function()
		expect(function() Scope.New({}) end):toFail("Scope.New: id must be a non-empty string")
		local scope = Scope.New({ id = "bare" })
		expect(function() scope:On("e", function() end) end):toFail("no event bus")
		expect(function() scope:Every("j", 1, function() end) end):toFail("no scheduler")
		expect(function() scope:After(1, function() end) end):toFail("no scheduler")
		local ran = false
		scope:Defer(function() ran = true end)
		scope:Dispose()
		expect(ran):toBe(true)
	end)
end)
